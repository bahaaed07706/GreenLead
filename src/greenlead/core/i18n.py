def get_translations(lang: str) -> dict[str, str]:
    return TRANSLATIONS.get(lang, TRANSLATIONS["ar"])


def format_translation(lang: str, key: str, **kwargs: Any) -> str:
    text = TRANSLATIONS.get(lang, TRANSLATIONS["ar"]).get(key, key)
    return text.format(**kwargs) if kwargs else text


def _current_identity(request: Request) -> tuple[str, str]:
    """Best-effort (username, role) from the session cookie; ('','') if none.

    Never raises — used only for conditional UI (e.g. the admin nav link).
    Authorization itself is always enforced server-side by route dependencies.
    """
    token = request.cookies.get("session")
    if not token:
        return "", ""
    from greenlead.core.security import verify_session_token

    username = verify_session_token(token)
    if not username:
        return "", ""
    try:
        from greenlead.repositories import get_user_repository

        user = get_user_repository().get_user_by_username(username)
        return (username, user.role) if user else (username, "")
    except Exception:  # noqa: BLE001
        return username, ""


def get_lang_context(request: Request) -> dict[str, Any]:
    lang = request.cookies.get("lang", "ar")
    if lang not in TRANSLATIONS:
        lang = "ar"
    username, role = _current_identity(request)
    settings = get_settings()
    return {
        "lang": lang,
        "dir": "rtl" if lang == "ar" else "ltr",
        "t": get_translations(lang),
        "current_username": username,
        "current_role": role,
        # Branding — configurable per deployment (see docs/CUSTOMIZATION.md).
        "org_name": settings.org_name,
        "org_industry": settings.org_industry,
    }
